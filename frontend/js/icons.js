/**
 * Returns an SVG markup string for a given icon.
 * @param {string} name - Name of icon (e.g. 'crown', 'search', 'plus')
 * @param {object} [opts] - Size, color, className, strokeWidth
 * @returns {string} - Complete SVG HTML string
 */
export function renderIcon(name, { size = 18, color = 'currentColor', className = '', strokeWidth = 2 } = {}) {
  const normalizedKey = name ? String(name).replace(/-([a-z])/g, (_, c) => c.toUpperCase()) : '';
  const content = ICONS[name] || ICONS[normalizedKey] || ICONS[name?.toLowerCase()] || ICONS.alertCircle;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" class="${className}">${content}</svg>`;
}

/**
 * Backward-compatible helper for modals using getIcon(name, className).
 */
export function getIcon(name, className = '') {
  let size = 18;
  if (className.includes('icon-sm')) size = 14;
  else if (className.includes('icon-md')) size = 20;
  else if (className.includes('icon-lg')) size = 28;
  return renderIcon(name, { size, className });
}
